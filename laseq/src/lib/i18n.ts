export const MESSAGES: Record<Locale, Dict> = { en, ar };

export function getDict(locale: Locale): Dict {
  return MESSAGES[locale] ?? MESSAGES[DEFAULT_LOCALE];
}

export function isLocale(v: unknown): v is Locale {
  return v === "ar" || v === "en";
}

export function dirFor(locale: Locale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

/** Look up an enum label like st_ACTIVE, falling back to the raw value. */
export function enumLabel(dict: Dict, prefix: "st" | "bt" | "rh" | "pl" | "pm", value: string): string {
  const key = `${prefix}_${value}` as MessageKey;
  return (dict[key] as string | undefined) ?? value;
}
